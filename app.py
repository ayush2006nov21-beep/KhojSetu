@app.route("/admin/report/<int:report_id>/verification", methods=["POST"])
def update_verification(report_id):
    if "user_id" not in session:
        flash("Please log in to continue.")
        return redirect(url_for("login"))

    if not is_current_user_admin():
        flash("You do not have permission to perform this action.")
        return redirect(url_for("home"))

    new_verification = request.form.get("verification_status", "").strip()
    if new_verification not in ["Approved", "Rejected", "Pending"]:
        flash("Invalid verification status.")
        return redirect(url_for("admin_dashboard"))

    with get_db() as db:
        db.row_factory = sqlite3.Row
        report = db.execute("""
            SELECT id, report_type, item_name, owner_id, verification_status
            FROM reports
            WHERE id = ?
        """, (report_id,)).fetchone()

        if report is None:
            flash("Report not found.")
            return redirect(url_for("admin_dashboard"))

        old_verification = report["verification_status"]

        db.execute("""
            UPDATE reports
            SET verification_status = ?
            WHERE id = ?
        """, (new_verification, report_id))

        # Notify the report owner only when the verification status changes.
        if (
            report["owner_id"] is not None
            and old_verification != new_verification
        ):
            db.execute("""
                INSERT INTO notifications (user_id, message)
                VALUES (?, ?)
            """, (
                report["owner_id"],
                (
                    f"Your {report['report_type']} report "
                    f"'{report['item_name']}' has been "
                    f"{new_verification.lower()} by the admin."
                )
            ))

    flash(f"Report #{report_id} marked as {new_verification.lower()}.")
    return redirect(url_for("admin_dashboard"))


