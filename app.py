# Make the unread notification count available to all templates.
@app.context_processor
def inject_unread_notification_count():
    unread_notification_count = 0

    if "user_id" in session:
        try:
            with get_db() as db:
                unread_notification_count = db.execute("""
                    SELECT COUNT(*)
                    FROM notifications
                    WHERE user_id = ? AND is_read = 0
                """, (session["user_id"],)).fetchone()[0]
        except psycopg.Error:
            # Keep pages usable if the notifications table is not yet initialized.
            unread_notification_count = 0

    return {"unread_notification_count": unread_notification_count}


