# Image validation
def valid_image(image, extension):
    image.seek(0)
    header = image.read(12)
    image.seek(0)

    if extension in [".jpg", ".jpeg"]:
        return header.startswith(b"\xff\xd8\xff")

    if extension == ".png":
        return header.startswith(b"\x89PNG\r\n\x1a\n")

    if extension == ".webp":
        return (
            len(header) >= 12
            and header[:4] == b"RIFF"
            and header[8:12] == b"WEBP"
        )

    return False


@app.route("/uploads/<path:key>")
def uploaded_image(key):
    """Redirect to a short-lived download URL for a private uploaded image."""
    if not key.startswith("uploads/"):
        return "Not found", 404
    url = get_storage_client().generate_presigned_url(
        "get_object",
        Params={
            "Bucket": os.getenv("S3_BUCKET") or os.getenv("BUCKET_NAME"),
            "Key": key,
        },
        ExpiresIn=3600,
    )
    return redirect(url)


