def create_table():
    with get_db() as db:

        db.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL UNIQUE,
                email TEXT NOT NULL UNIQUE,
                password TEXT NOT NULL,
                is_admin INTEGER DEFAULT 0,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS reports (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                report_type TEXT NOT NULL,
                item_name TEXT NOT NULL,
                description TEXT NOT NULL,
                location TEXT NOT NULL,
                date TEXT NOT NULL,
                category TEXT DEFAULT 'Other',
                status TEXT DEFAULT 'Open',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                image_path TEXT,
                owner_id INTEGER REFERENCES users(id),
                verification_status TEXT DEFAULT 'Pending'
            )
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS claims (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                lost_report_id INTEGER NOT NULL REFERENCES reports(id),
                found_report_id INTEGER NOT NULL REFERENCES reports(id),
                claimant_id INTEGER NOT NULL REFERENCES users(id),
                finder_id INTEGER NOT NULL REFERENCES users(id),
                ownership_details TEXT NOT NULL,
                status TEXT DEFAULT 'Pending',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP
            )
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS notifications (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id),
                message TEXT NOT NULL,
                claim_id INTEGER REFERENCES claims(id),
                is_read INTEGER DEFAULT 0,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        db.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS is_admin INTEGER DEFAULT 0")
