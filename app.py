# Lost and Found reporting
@app.route("/report/<report_type>", methods=["GET", "POST"])
def report(report_type):

    if "user_id" not in session:
        flash("Please log in before submitting a lost or found report.")
        return redirect(url_for("login"))

    if report_type not in ["lost", "found"]:
        return "Invalid report type", 404

    message = ""
    matches = []
    new_id = None

    if request.method == "POST":

        item_name = request.form.get("item_name", "").strip()
        description = request.form.get("description", "").strip()
        location = request.form.get("location", "").strip()
        date = request.form.get("date", "").strip()
        category = request.form.get("category", "Other").strip()

        allowed_categories = [
            "Electronics", "Bags", "Documents",
            "Accessories", "Clothing", "Books", "Other"
        ]

        if category not in allowed_categories:
            category = "Other"

        image = request.files.get("item_image")
        image_path = None

        if not all([item_name, description, location, date]):
            message = "Please fill in all the fields."

        elif image and image.filename:

            extension = Path(image.filename).suffix.lower()

            if extension not in ALLOWED_EXTENSIONS:
                message = "Only JPG, PNG and WEBP images are allowed."

            else:
                image.seek(0, os.SEEK_END)
                image_size = image.tell()
                image.seek(0)

                if image_size == 0:
                    message = "The uploaded image is empty."
                elif image_size > MAX_IMAGE_SIZE:
                    message = "Image size must be below 5 MB."
                elif not valid_image(image, extension):
                    message = "The uploaded file is not a valid image."

        if not message:

            if image and image.filename:
                original_name = secure_filename(image.filename)
                unique_name = f"{uuid.uuid4().hex}_{original_name}"
                image_path = f"uploads/{unique_name}"
                get_storage_client().upload_fileobj(
                    image,
                    os.getenv("S3_BUCKET") or os.getenv("BUCKET_NAME"),
                    image_path,
                    ExtraArgs={"ContentType": image.mimetype or "application/octet-stream"},
                )

            try:
                with get_db() as db:
                    db.row_factory = sqlite3.Row

                    cursor = db.execute("""
                        INSERT INTO reports
                        (report_type, item_name, description,
                         location, date, category, image_path, owner_id)
                        VALUES (?, ?, ?, ?, ?, ?, ?, ?) RETURNING id
                    """, (
                        report_type, item_name, description,
                        location, date, category, image_path,
                        session["user_id"]
                    ))

                    new_id = cursor.fetchone()["id"]

                    new_report = db.execute("""
                        SELECT * FROM reports WHERE id = ?
                    """, (new_id,)).fetchone()

                    opposite_type = (
                        "found" if report_type == "lost" else "lost"
                    )

                    if new_report["verification_status"] == "Approved":
                        candidates = db.execute("""
                            SELECT * FROM reports
                            WHERE report_type = ?
                            AND status = 'Open'
                            AND verification_status = 'Approved'
                            AND id != ?
                        """, (opposite_type, new_id)).fetchall()
                    else:
                        candidates = []

                    for candidate in candidates:
                        score = calculate_match(
                            dict(new_report), dict(candidate)
                        )

                        if score >= 40:
                            matches.append({
                                "id": candidate["id"],
                                "item_name": candidate["item_name"],
                                "description": candidate["description"],
                                "location": candidate["location"],
                                "date": candidate["date"],
                                "category": candidate["category"],
                                "image_path": candidate["image_path"],
                                "match_score": score
                            })

                    matches.sort(
                        key=lambda item: item["match_score"],
                        reverse=True
                    )

                message = (
                    "Your report has been submitted successfully and is waiting "
                    "for admin approval. Possible matches will appear in My Reports "
                    "after the report is approved."
                )

                if matches:
                    message = "Your report has been saved and possible matches were found!"

            except Exception:
                if image_path:
                    try:
                        get_storage_client().delete_object(
                            Bucket=os.getenv("S3_BUCKET") or os.getenv("BUCKET_NAME"),
                            Key=image_path,
                        )
                    except Exception:
                        app.logger.exception("Unable to remove an orphaned upload")

                app.logger.exception("Report submission failed")
                message = "Unable to save your report. Please try again."

    return render_template(
        "report.html",
        report_type=report_type,
        message=message,
        matches=matches,
        report_id=new_id
    )


# Logged-in user's reports dashboard
@app.route("/my-reports")
def my_reports():
    if "user_id" not in session:
        flash("Please log in to view your reports.")
        return redirect(url_for("login"))

    with get_db() as db:
        db.row_factory = sqlite3.Row

        user_reports = db.execute("""
            SELECT * FROM reports
            WHERE owner_id = ?
            ORDER BY id DESC
        """, (session["user_id"],)).fetchall()

        dashboard_reports = []

        for user_report in user_reports:
            opposite_type = (
                "found" if user_report["report_type"] == "lost" else "lost"
            )

            if user_report["verification_status"] == "Approved":
                candidates = db.execute("""
                    SELECT * FROM reports
                    WHERE report_type = ?
                    AND status = 'Open'
                    AND verification_status = 'Approved'
                    AND id != ?
                """, (opposite_type, user_report["id"])).fetchall()
            else:
                candidates = []

            possible_matches = []

            for candidate in candidates:
                score = calculate_match(
                    dict(user_report), dict(candidate)
                )

                if score >= 40:
                    possible_matches.append({
                        "id": candidate["id"],
                        "item_name": candidate["item_name"],
                        "match_score": score
                    })

            possible_matches.sort(
                key=lambda item: item["match_score"],
                reverse=True
            )

            dashboard_reports.append({
                "report": user_report,
                "matches": possible_matches
            })

    return render_template(
        "my_reports.html",
        dashboard_reports=dashboard_reports
    )


