        db.execute("ALTER TABLE reports ADD COLUMN IF NOT EXISTS image_path TEXT")
        db.execute("ALTER TABLE reports ADD COLUMN IF NOT EXISTS owner_id INTEGER REFERENCES users(id)")
        db.execute("ALTER TABLE reports ADD COLUMN IF NOT EXISTS verification_status TEXT DEFAULT 'Pending'")

