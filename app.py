# Find possible matches
@app.route("/matches/<int:report_id>")
def find_matches(report_id):

    with get_db() as db:
        db.row_factory = sqlite3.Row

        report = db.execute("""
            SELECT * FROM reports
            WHERE id = ? AND verification_status = 'Approved'
        """, (report_id,)).fetchone()

        if report is None:
            return jsonify({"error": "Report not found or not approved"}), 404

        opposite_type = (
            "found" if report["report_type"] == "lost" else "lost"
        )

        candidates = db.execute("""
            SELECT * FROM reports
            WHERE report_type = ?
            AND status = 'Open'
            AND verification_status = 'Approved'
        """, (opposite_type,)).fetchall()

        matches = []

        for candidate in candidates:
            score = calculate_match(
                dict(report), dict(candidate)
            )

            if score >= 40:
                matches.append({
                    "id": candidate["id"],
                    "item_name": candidate["item_name"],
                    "description": candidate["description"],
                    "location": candidate["location"],
                    "date": candidate["date"],
                    "category": candidate["category"],
                    "image_path": candidate["image_path"],
                    "match_score": score
                })

        matches.sort(
            key=lambda item: item["match_score"],
            reverse=True
        )

    return jsonify({
        "report_id": report_id,
        "matches_found": len(matches),
        "matches": matches
    })


