@app.route("/transcribe", methods=["POST"])
def transcribe():

    audio = request.files.get("audio")
    language = request.form.get("language", "hi-IN")

    if not audio or audio.filename == "":
        return jsonify({"error": "Please select an audio file"}), 400

    if language not in ["hi-IN", "en-IN"]:
        return jsonify({"error": "Invalid language"}), 400

    temp_path = None

    try:
        with tempfile.NamedTemporaryFile(
            suffix=".wav", delete=False
        ) as temp:
            temp_path = temp.name

        audio.save(temp_path)

        from services.prisma import transcribe_audio
        text = transcribe_audio(temp_path, language)

        return jsonify({"transcript": text})

    except Exception:
        app.logger.exception("Voice transcription failed")
        return jsonify({
            "error": "Voice transcription failed. Please try again."
        }), 500

    finally:
        if temp_path and os.path.exists(temp_path):
            os.remove(temp_path)


