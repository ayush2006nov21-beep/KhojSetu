# Submit an ownership claim for a possible match
@app.route("/claim/<int:lost_report_id>/<int:found_report_id>", methods=["POST"])
def submit_claim(lost_report_id, found_report_id):
    if "user_id" not in session:
        flash("Please log in before submitting a claim.")
        return redirect(url_for("login"))

    ownership_details = request.form.get("ownership_details", "").strip()
    if len(ownership_details) < 10:
        flash("Please provide at least 10 characters describing proof of ownership.")
        return redirect(url_for(
            "match_details",
            report_id=lost_report_id,
            match_id=found_report_id
        ))

    if len(ownership_details) > 1000:
        flash("Ownership details must be 1000 characters or fewer.")
        return redirect(url_for(
            "match_details",
            report_id=lost_report_id,
            match_id=found_report_id
        ))

    with get_db() as db:
        db.row_factory = sqlite3.Row
        lost_report = db.execute("""
            SELECT * FROM reports
            WHERE id = ? AND report_type = 'lost'
            AND verification_status = 'Approved'
        """, (lost_report_id,)).fetchone()

        found_report = db.execute("""
            SELECT * FROM reports
            WHERE id = ? AND report_type = 'found'
            AND verification_status = 'Approved'
        """, (found_report_id,)).fetchone()

        if not lost_report or not found_report:
            flash("These reports are not available for claiming.")
            return redirect(url_for("my_reports"))

        if lost_report["owner_id"] != session["user_id"]:
            flash("Only the owner of the lost-item report can submit this claim.")
            return redirect(url_for("my_reports"))

        if found_report["owner_id"] == session["user_id"]:
            flash("You cannot claim your own found-item report.")
            return redirect(url_for("my_reports"))

        if lost_report["status"] != "Open" or found_report["status"] != "Open":
            flash("A claim can only be submitted for reports that are still open.")
            return redirect(url_for(
                "match_details",
                report_id=lost_report_id,
                match_id=found_report_id
            ))

        existing = db.execute("""
            SELECT id FROM claims
            WHERE lost_report_id = ? AND found_report_id = ?
            AND claimant_id = ? AND status = 'Pending'
        """, (lost_report_id, found_report_id, session["user_id"])).fetchone()

        if existing:
            flash("You already have a pending claim for this match.")
            return redirect(url_for("my_claims"))

        claim_cursor = db.execute("""
            INSERT INTO claims
            (lost_report_id, found_report_id, claimant_id, finder_id, ownership_details)
            VALUES (?, ?, ?, ?, ?) RETURNING id
        """, (
            lost_report_id,
            found_report_id,
            session["user_id"],
            found_report["owner_id"],
            ownership_details
        ))
        claim_id = claim_cursor.fetchone()["id"]
        db.execute("""
            INSERT INTO notifications (user_id, message, claim_id)
            VALUES (?, ?, ?)
        """, (
            found_report["owner_id"],
            "Someone has submitted an ownership claim for an item you found.",
            claim_id
        ))

    flash("Your claim has been sent to the person who found the item.")
    return redirect(url_for("my_claims"))


# View claims sent by you and claims received by you
@app.route("/my-claims")
def my_claims():
    if "user_id" not in session:
        flash("Please log in to view claims.")
        return redirect(url_for("login"))

    with get_db() as db:
        db.row_factory = sqlite3.Row
        claims = db.execute("""
            SELECT claims.*,
                   lost.item_name AS lost_item_name,
                   lost.location AS lost_location,
                   found.item_name AS found_item_name,
                   found.location AS found_location,
                   claimant.username AS claimant_name,
                   finder.username AS finder_name
            FROM claims
            JOIN reports AS lost ON claims.lost_report_id = lost.id
            JOIN reports AS found ON claims.found_report_id = found.id
            LEFT JOIN users AS claimant ON claims.claimant_id = claimant.id
            LEFT JOIN users AS finder ON claims.finder_id = finder.id
            WHERE claims.claimant_id = ? OR claims.finder_id = ?
            ORDER BY claims.id DESC
        """, (session["user_id"], session["user_id"])).fetchall()

    return render_template("my_claims.html", claims=claims)


# Finder responds to a claim
@app.route("/claim/<int:claim_id>/decision", methods=["POST"])
def decide_claim(claim_id):
    if "user_id" not in session:
        flash("Please log in to respond to a claim.")
        return redirect(url_for("login"))

    decision = request.form.get("decision", "").strip()
    if decision not in ["Accepted", "Rejected"]:
        flash("Invalid claim decision.")
        return redirect(url_for("my_claims"))

    with get_db() as db:
        db.row_factory = sqlite3.Row
        claim = db.execute("""
            SELECT * FROM claims WHERE id = ?
        """, (claim_id,)).fetchone()

        if not claim:
            flash("Claim not found.")
            return redirect(url_for("my_claims"))

        if claim["finder_id"] != session["user_id"]:
            flash("Only the person who found the item can respond to this claim.")
            return redirect(url_for("my_claims"))

        if claim["status"] != "Pending":
            flash("This claim has already been reviewed.")
            return redirect(url_for("my_claims"))

        db.execute("""
            UPDATE claims
            SET status = ?, updated_at = CURRENT_TIMESTAMP
            WHERE id = ?
        """, (decision, claim_id))
        db.execute("""
            INSERT INTO notifications (user_id, message, claim_id)
            VALUES (?, ?, ?)
        """, (
            claim["claimant_id"],
            f"The finder has {decision.lower()} your ownership claim.",
            claim_id
        ))

    if decision == "Accepted":
        flash("Claim accepted. Please arrange a safe ownership verification before returning the item.")
    else:
        flash("Claim rejected.")

    return redirect(url_for("my_claims"))


